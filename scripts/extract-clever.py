"""Extract the supplied Clever sheets and retain the four Chinese rulebooks.

Usage: python scripts/extract-clever.py <source-directory>
Requires pypdfium2 and Pillow. Source PDFs are never modified.
"""
from pathlib import Path
import json
import shutil
import sys
import pypdfium2 as pdfium
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
out = root / 'public/assets/clever'
out.mkdir(parents=True, exist_ok=True)
assets = []
for key, title, version in [
    ('one', '绝顶聪明', 1), ('two', '双倍聪明', 2),
    ('three', '三倍聪明', 3), ('four', '四倍聪明', 4),
    ('challenge-one', '挑战模式1', 1), ('challenge-two', '挑战模式2', 2),
    ('challenge-three', '挑战模式3', 3),
]:
    doc = pdfium.PdfDocument(source / f'{title}.pdf')
    page = doc[0]
    page.render(scale=3).to_pil().convert('RGB').save(out / f'{key}.webp', quality=94)
    assets.append(dict(id=f'clever-{key}', type='board', name=title, group='sheet',
                       groupLabel='计分纸', width=720, height=720*842/595,
                       front=f'/assets/clever/{key}.webp', version=version, sheet=key))
    page.close()
    doc.close()

colors = dict(yellow='#eecb26', blue='#277bbc', green='#94bc35', orange='#ef9335',
              purple='#7756aa', pink='#e979bc', silver='#a1a2a6', teal='#49b9b5',
              brown='#a97946', white='#eeeae0')
patterns = {1:[4], 2:[0,8], 3:[0,4,8], 4:[0,2,6,8], 5:[0,2,4,6,8], 6:[0,2,3,5,6,8]}
for color, fill in colors.items():
    for value, pips in patterns.items():
        im = Image.new('RGB', (144,144), fill)
        draw = ImageDraw.Draw(im)
        draw.rounded_rectangle((3,3,140,140), radius=22, fill=fill, outline='#ffffff', width=4)
        for pip in pips:
            row, col = divmod(pip, 3)
            x, y = 35+col*37, 35+row*37
            draw.ellipse((x-10,y-10,x+10,y+10), fill='#28323b')
        im.save(out / f'die-{color}-{value}.webp', quality=94)
for version in range(1,5):
    shutil.copyfile(source / f'clever{version}rule.pdf', out / f'rules-{version}-zh.pdf')
(root / 'src/games/clever-assets.js').write_text(
    '// Generated by scripts/extract-clever.py.\nexport const cleverAssets = '+
    json.dumps(assets, ensure_ascii=False, indent=2)+';\n', encoding='utf-8')
print(f'Extracted {len(assets)} sheets, 60 dice faces and four rulebooks to {out}')
