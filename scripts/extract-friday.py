"""Extract the user-supplied Chinese Friday sheets. Requires Pillow only.

Usage: python scripts/extract-friday.py <source-directory>
Cells are numbered in reading order, two columns by five rows. Fighting
cards are rotated clockwise; pirates keep their printed landscape layout.
"""
from pathlib import Path
import json
import shutil
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[1])
OUT = ROOT / 'public/assets/friday'
OUT.mkdir(parents=True, exist_ok=True)
pages = {}
assets = []

def page(name):
    if name not in pages:
        pages[name] = Image.open(SOURCE / f'{name}.png').convert('RGB')
    return pages[name]

def save(im, code):
    im.save(OUT / f'{code}.webp', quality=91, method=6)
    return f'/assets/friday/{code}.webp'

def cell(sheet, n, code, rotate=True):
    row, col = divmod(n-1, 2)
    # Inset from the printed crop marks, retaining the rounded cream corners.
    x, y = 38 + col*1240, 96 + row*666
    im = page(sheet).crop((x, y, x+1156, y+638))
    if rotate:
        im = im.transpose(Image.Transpose.ROTATE_270)
    return save(im, code)

back = cell('1b', 1, 'card-back')
pirate_back = cell('7b', 1, 'pirate-back', False)
labels = {'starting':'鲁宾逊起始卡','aging':'衰老卡','hazard':'危险／知识卡','pirate':'海盗','phase':'进度卡','mat':'放置图板'}

def add(code, name, group, sheet, n, **data):
    rotate = group != 'pirate'
    assets.append(dict(id='fr-'+code, type='card', name=name, group=group,
        groupLabel=labels[group], width=140 if rotate else 254,
        height=254 if rotate else 140, front=cell(sheet,n,code,rotate),
        back=pirate_back if group=='pirate' else back,
        sourceSheet=sheet, sourceCell=n, **data))

starting = [(-1,'发呆')]*5 + [(0,'进食 · +2生命')] + [(2,'天才')] + [(0,'虚弱')]*3
starting += [(1,'专注')]*3 + [(0,'虚弱')]*5
for i, (value,name) in enumerate(starting):
    add(f'start-{i+1}',name,'starting','1a' if i<10 else '2a',i%10+1,fight=value,destroyCost=1)

aging = [('very-stupid',-3,'老年痴呆','2a',9,False),('suicide',-5,'自杀','2a',10,True),
    ('stupid-1',-2,'痴呆','3a',2,False),('stupid-2',-2,'痴呆','3a',3,False),
    ('idiotic',-4,'低能','3a',4,True),('distracted',-1,'发呆','3a',5,False),
    ('hungry-2',0,'非常饥饿 · -2生命','3a',6,True),('stop',0,'极度疲倦 · 停止','3a',7,False),
    ('hungry-1',0,'饥饿 · -1生命','3a',8,False),('highest-1',0,'惊吓 · 最高牌=0','3a',9,False),
    ('highest-2',0,'惊吓 · 最高牌=0','3a',10,False)]
for code,value,name,sheet,n,hard in aging:
    add('aging-'+code,name,'aging',sheet,n,fight=value,hard=hard,destroyCost=2)

knowledge = [
    ('策略 · 2次交换',0),('策略 · 2次交换',0),('诡计 · 牌堆底',0),('领悟 · 摧毁',0),('模仿 · 复制',0),('书籍 · 阶段-1',0),('装备 · +2张牌',0),('装备 · +2张牌',0),('诡计 · 牌堆底',1),('领悟 · 摧毁',1),
    ('食物 · +1生命',1),('食物 · +1生命',1),('模仿 · 复制',1),('再来一次 · 加倍',1),('策略 · 交换',2),('经验 · +1张牌',2),('领悟 · 摧毁',2),('食物 · +1生命',2),('武器',2),('武器',2),
    ('预知 · 看3张牌',2),('再来一次 · 加倍',2),('策略 · 交换',3),('经验 · +1张牌',3),('领悟 · 摧毁',3),('预知 · 看3张牌',3),('武器',4),('武器',4),('食物 · +1生命',0),('食物 · +1生命',0)]
for i,(name,value) in enumerate(knowledge):
    n=i+1
    band=0 if n<=8 or n>=29 else 1 if n<=14 or 19<=n<=20 else 2 if n<=18 or n<=22 else 3 if n<=26 else 4
    title,free,values=[('乘木筏登破船',1,[0,1,3]),('探索岛屿',2,[1,3,6]),('深入岛屿',3,[2,5,8]),('野兽',4,[4,7,11]),('食人族',5,[5,9,14])][band]
    add(f'hazard-{n}',title+' / '+name,'hazard',f'{4+i//10}a',i%10+1,fight=value,free=free,hazard=values,destroyCost=1)

pirates=[('剩余危险',None,None),('衰老牌加难',5,None),('普通海盗',6,20),('额外牌支付2生命',7,16),('普通海盗',7,25),('普通海盗',8,30),('一半战斗牌',9,22),('普通海盗',9,35),('普通海盗',10,40),('每张战斗牌+1',10,52)]
for i,(name,free,value) in enumerate(pirates):
    add(f'pirate-{i+1}',name,'pirate','7a',i+1,free=free,pirateValue=value)

for name,sheet,n in [('green','8a',2),('yellow','8a',1),('red','3a',1)]:
    add('phase-'+name,{'green':'绿色阶段','yellow':'黄色阶段','red':'红色阶段'}[name],'phase',sheet,n)

for code,name,box in [('hazard','危险',(38,762,1194,1934)),('robinson','鲁宾逊',(1278,762,2434,1934)),('aging','衰老',(38,2232,1194,3406))]:
    assets.append(dict(id='fr-mat-'+code,type='board',name=name+'放置图板',group='mat',groupLabel=labels['mat'],width=255,height=259,front=save(page('8a').crop(box),'mat-'+code)))

leaf=page('8a').crop((1600,2550,1748,2718)).convert('RGBA')
# The supplied leaf has a white background; alpha preserves its original art.
leaf.putdata([(r,g,b,0 if min(r,g,b)>240 else 255) for r,g,b,a in leaf.getdata()])
save(leaf,'life-leaf')
(ROOT/'src/games/friday-assets.js').write_text('// Generated by scripts/extract-friday.py\nexport const fridayAssets = '+json.dumps(assets,ensure_ascii=False,indent=2)+';\n',encoding='utf8')
shutil.copyfile(SOURCE/'FridayRulesSCh.pdf',OUT/'rules-zh.pdf')
print(f'Extracted {len(assets)} assets and copied Chinese rules.')
