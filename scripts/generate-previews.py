"""Regenerate the lightweight plaza catalog and cover thumbnails (requires Pillow)."""
import json
import subprocess
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CATALOG_SOURCE = """
import {examples} from './src/projects.js';
const boards=new Set();
const catalog=examples.map(game=>{
  const session=game.create(()=>.5),available=session.assets.filter(a=>a.type==='card');
  for(const asset of session.assets)if(asset.type==='board')boards.add(asset.front);
  const covers=(game.coverAssetIds||[]).map(id=>available.find(a=>a.id===id)).filter(Boolean);
  const cards=(covers.length?covers:available).slice(0,3);
  const assets=cards.length?cards:session.assets.filter(a=>a.type==='board'||a.type==='token').slice(0,1);
  return {id:game.id,title:game.title,legacyName:session.name,
    ...(game.coverAssetIds?{coverAssetIds:game.coverAssetIds}:{}),
    preview:{gameId:game.id,name:game.title,meta:session.meta,
      assets:assets.map(({id,type,front,width,height})=>({id,type,front,width,height}))}};
});
console.log(JSON.stringify({catalog,boards:[...boards]}));
"""

generated = json.loads(subprocess.check_output(
    ["node", "--input-type=module", "-e", CATALOG_SOURCE], cwd=ROOT, encoding="utf-8"))
catalog = generated["catalog"]
original_bytes = preview_bytes = 0
for game in catalog:
    for asset in game["preview"]["assets"]:
        original = ROOT / "public" / asset["front"].lstrip("/")
        relative = Path(asset["front"].removeprefix("/assets/"))
        target = ROOT / "public/assets/previews" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(original) as image:
            image.thumbnail((256, 384), Image.Resampling.LANCZOS)
            image.save(target, "WEBP", quality=75, method=6)
            asset["thumbnail"] = "/assets/previews/" + relative.as_posix()
            asset["thumbnailWidth"], asset["thumbnailHeight"] = image.size
        original_bytes += original.stat().st_size
        preview_bytes += target.stat().st_size

source = "// Generated by scripts/generate-previews.py; keep game images at full resolution.\n"
source += "export const exampleCatalog=" + json.dumps(catalog, ensure_ascii=False, separators=(",", ":")) + ";\n"
(ROOT / "src/example-catalog.js").write_text(source, encoding="utf-8")
print(f"Cover images: {original_bytes:,} -> {preview_bytes:,} bytes ({100 * (1-preview_bytes/original_bytes):.1f}% smaller)")

boards = {}
board_original_bytes = board_preview_bytes = 0
for front in generated["boards"]:
    original = ROOT / "public" / front.lstrip("/")
    if original.stat().st_size < 250 * 1024:
        continue
    relative = Path(front.removeprefix("/assets/"))
    target = ROOT / "public/assets/previews/boards" / relative
    with Image.open(original) as image:
        width, height = image.size
        if max(width, height) <= 1600:
            continue
        image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
        target.parent.mkdir(parents=True, exist_ok=True)
        image.save(target, "WEBP", quality=82, method=6)
        boards[front] = {"src": "/assets/previews/boards/" + relative.as_posix(),
                         "width": image.width, "height": image.height,
                         "originalWidth": width, "originalHeight": height}
    board_original_bytes += original.stat().st_size
    board_preview_bytes += target.stat().st_size

source = "// Generated by scripts/generate-previews.py; original board images remain in saved projects.\n"
source += "export const boardPreviews=" + json.dumps(boards, ensure_ascii=False, separators=(",", ":")) + ";\n"
(ROOT / "src/board-previews.js").write_text(source, encoding="utf-8")
print(f"Board images: {len(boards)} previews, {board_original_bytes:,} -> {board_preview_bytes:,} bytes")
