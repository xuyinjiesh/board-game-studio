"""Extract the supplied four-page Pocket Paladin PnP, preserving both faces."""
from pathlib import Path
import json
import sys
import pypdfium2 as pdfium
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
if len(sys.argv) != 2:
    raise SystemExit('Usage: provide the source PDF or directory as the first argument.')
source = Path(sys.argv[1])
out = root/'public/assets/pocket-paladin'
out.mkdir(parents=True, exist_ok=True)
doc = pdfium.PdfDocument(source)
pages = [p.render(scale=3).to_pil().convert('RGB') for p in doc]
assets=[]
def crop(page, box, name, rotate=0, circle=False, hexagon=False):
    im=pages[page-1].crop(tuple(round(x*3) for x in box))
    if rotate: im=im.rotate(rotate,expand=True)
    if circle:
        im=im.convert('RGBA');mask=Image.new('L',im.size);ImageDraw.Draw(mask).ellipse((0,0,im.width-1,im.height-1),fill=255);im.putalpha(mask)
    if hexagon:
        im=im.convert('RGBA');w,h=im.size;mask=Image.new('L',im.size);ImageDraw.Draw(mask).polygon([(w/4,0),(w*3/4,0),(w-1,h/2),(w*3/4,h-1),(w/4,h-1),(0,h/2)],fill=255);im.putalpha(mask)
    im.save(out/f'{name}.webp',quality=93)
    return f'/assets/pocket-paladin/{name}.webp'
def add(code,name,group,w,h,front,back=None,**kw):
    assets.append(dict(id='pp-'+code,type='card',name=name,group=group,groupLabel={'map':'地图','hero':'骑士','track':'状态与能力','enemy':'敌人／盟友／技能','shard':'水晶转盘'}[group],width=w,height=h,front=front,back=back or front,**kw))
for i in range(16):
    row,col=divmod(i,10);x=17+col*74.5;y=58+row*74.5
    f=crop(2,(x,y,x+74,y+74),f'enemy-{i+1}',circle=True)
    b=crop(1,(x,y,x+74,y+74),f'ally-{i+1}',circle=True)
    # The frame behind each enemy is red (monster) or purple (mage).
    # Printed order: alternate types are deliberately mixed on the sheet.
    add(f'enemy-{i+1}',f'{"法师" if i<8 else "怪物"}／盟友／技能 {i+1:02d}','enemy',68,68,f,b,enemyType='mage' if i<8 else 'monster')
add('hero','红／紫骑士','hero',48,48,crop(1,(464,133,539,208),'hero-red',circle=True),crop(2,(464,133,539,208),'hero-purple',circle=True))
for code,name,box in [('ability','能力路线',(314,233,513,504)),('tracks','状态轨道',(552,233,752,504))]:
    add(code,name,'track',360,264,crop(1,box,code+'-red',rotate=270),crop(2,box,code+'-purple',rotate=270))
for i,(code,name,box) in enumerate([('blue','蓝水晶',(17,219,107,298)),('black','黑水晶',(117,219,207,298)),('source','水晶源',(17,309,107,388)),('purple','紫水晶',(117,309,207,388))]):
    add(code,name,'shard',70,61,crop(1,box,code,hexagon=True))
for i,(x,label) in enumerate([(117,'A'),(390,'B')]):
    box=(x,86,x+273,454)
    add('map-'+label,'地图 '+label,'map',280,377.44,crop(3,box,'map-'+label),crop(4,box,'map-'+label+'-castle'))
(root/'src/games/pocket-paladin-assets.js').write_text('// Generated by scripts/extract-pocket-paladin.py\nexport const pocketPaladinAssets = '+json.dumps(assets,ensure_ascii=False,indent=2)+';\n',encoding='utf8')
# A quiet table mat provides explicit ready / exhausted / XP areas.
im=Image.new('RGB',(1540,1100),'#17272a');d=ImageDraw.Draw(im)
font=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',18)
for box,title in [((35,90,435,210),'就绪盟友'),((35,510,435,630),'已学技能'),((35,660,435,800),'负伤盟友'),((1240,300,1505,500),'耗竭盟友／技能'),((1240,530,1505,710),'经验 · 塔楼敌人倒置'),((490,35,1040,150),'敌人牌堆与展示区'),((1100,750,1505,970),'城堡守军／当前战斗')]:
    d.rounded_rectangle(box,12,outline='#40575a',width=2);d.text((box[0]+16,box[1]+12),title,font=font,fill='#adc0ba')
d.text((40,30),'口袋骑士  /  POCKET PALADIN',font=font,fill='#d5c6a2')
im.save(out/'table.webp',quality=90)
print(f'Extracted {len(assets)} double-sided components.')
