"""Prepare supplied Chinese 52 Realms sheets and a locally drawn standard deck.

Usage: python scripts/extract-52-realms.py <asset-directory>
Requires Pillow. The source directory is read only.
"""
from pathlib import Path
import json
import shutil
import sys
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
sheets = source / '52 realms (2)'
out = root / 'public/assets/52-realms'
out.mkdir(parents=True, exist_ok=True)
assets = []

def save(im, name):
    im.convert('RGB').save(out / (name + '.webp'), quality=94)
    return '/assets/52-realms/' + name + '.webp'

maps = ['永恒游荡之魂的陵墓', '永恒午夜森林', '钟表匠的迷宫']
for i, name in enumerate(maps, 1):
    im = Image.open(sheets / f'{i}.png')
    front = save(im, f'map-{i}')
    assets.append(dict(id=f'realms-map-{i}', type='board', name=name, group='map',
                       width=700, height=990, front=front, mapNumber=i))

# Both halves are printed head-to-foot. Rotate the left half before cropping.
# Coordinates use the 700 x 990 sheet preview as their reference.
heroes = [('barbarian', '野蛮人', 25, 'a', False), ('wizard', '法师', 20, 'a', True),
          ('druid', '德鲁伊', 25, 'b', False), ('fallen-knight', '堕落骑士', 35, 'b', True),
          ('tinkerer', '修补匠', 20, 'c', False), ('hunter', '猎人', 25, 'c', True)]
for key, name, limit, sheet, left in heroes:
    im = Image.open(sheets / f'{sheet}.png').convert('RGB')
    w, h = im.size
    if left:
        im = im.rotate(180)
    box = tuple(round(v * (w / 700 if j % 2 == 0 else h / 990)) for j, v in enumerate((358, 0, 588, 574)))
    front = save(im.crop(box), 'hero-' + key)
    assets.append(dict(id='realms-hero-' + key, type='card', name=name, group='hero',
                       groupLabel='角色', width=230, height=574, front=front, back=front,
                       hero=key, woundLimit=limit))
    box = tuple(round(v * (w / 700 if j % 2 == 0 else h / 990)) for j, v in enumerate((590, 0, 700, 987)))
    front = save(im.crop(box), 'items-' + key)
    assets.append(dict(id='realms-items-' + key, type='board', name=name + ' · 物品效果',
                       group='reference', width=110, height=987, front=front))

# Original, font-drawn poker faces: no third-party playing-card artwork.
font_dir = Path('C:/Windows/Fonts')
def font(size, symbol=False):
    return ImageFont.truetype(str(font_dir / ('seguisym.ttf' if symbol else 'georgiab.ttf')), size)

back = Image.new('RGB', (320, 448), '#f7f3e7')
d = ImageDraw.Draw(back)
d.rounded_rectangle((13, 13, 306, 434), radius=12, fill='#18436a')
for x in range(-440, 760, 24):
    d.line((x, 20, x+410, 428), fill='#3b6182', width=2)
    d.line((x, 428, x+410, 20), fill='#3b6182', width=2)
d.rounded_rectangle((28, 28, 292, 420), radius=8, outline='#cab67c', width=3)
d.ellipse((89, 151, 231, 293), fill='#18436a', outline='#cab67c', width=3)
d.text((160, 219), '52', fill='#e8dbaf', font=font(65), anchor='mm')
back_url = save(back, 'card-back')
for suit, label, symbol, color in [('clubs', '梅花', '♣', '#202c35'), ('spades', '黑桃', '♠', '#202c35'),
                                    ('hearts', '红心', '♥', '#bd3341'), ('diamonds', '方块', '♦', '#bd3341')]:
    for number in range(1, 14):
        rank = {1:'A', 11:'J', 12:'Q', 13:'K'}.get(number, str(number))
        im = Image.new('RGB', (320, 448), '#fffdf5')
        d = ImageDraw.Draw(im)
        d.rounded_rectangle((2, 2, 317, 445), radius=17, outline='#d9d1bb', width=3)
        corner = Image.new('RGBA', (66, 118))
        cd = ImageDraw.Draw(corner)
        cd.text((33, 5), rank, fill=color, font=font(42 if number != 10 else 33), anchor='mt')
        cd.text((33, 50), symbol, fill=color, font=font(45, True), anchor='mt')
        im.paste(corner, (9, 7), corner)
        flipped = corner.rotate(180)
        im.paste(flipped, (245, 323), flipped)
        d.text((160, 192), symbol, fill=color, font=font(126, True), anchor='mm')
        d.text((160, 296), rank, fill=color, font=font(72), anchor='mm')
        front = save(im, f'{suit}-{number}')
        assets.append(dict(id=f'realms-{suit}-{number}', type='card', name=label + rank,
                           group='poker', groupLabel='标准扑克牌', suit=suit, rank=rank,
                           number=number, width=120, height=168, front=front, back=back_url))

for src, target in [(source/'中规.pdf', 'rules-zh.pdf'),
                    (sheets/'52 Realms Adventures Map 1 Rules V1.9.pdf', 'rules-map-1.pdf'),
                    (sheets/'52 Realms Adventures Map 2 Rules V1.2.pdf', 'rules-map-2.pdf'),
                    (sheets/'52 Realms Adventures Map 3 Rules V1.5.pdf', 'rules-map-3.pdf')]:
    shutil.copyfile(src, out/target)
(root/'src/games/52-realms-assets.js').write_text(
    '// Generated by scripts/extract-52-realms.py\nexport const realmsAssets = ' +
    json.dumps(assets, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
print(f'Prepared {len(assets)} assets and four rule PDFs.')
