"""Extract the supplied Chinese For Northwood! PnP (65 double-sided cards).

Usage: bundled-python scripts/extract-for-northwood.py <source-directory>
Requires pypdfium2 and Pillow. Coordinates follow the printed trim marks;
back cells are mirrored horizontally for long-edge duplex printing.
"""
from pathlib import Path
import json
import shutil
import sys
import pypdfium2 as pdfium

root = Path(__file__).resolve().parents[1]
if len(sys.argv) != 2:
    raise SystemExit('Usage: provide the source directory as the first argument.')
source = Path(sys.argv[1])
out = root / 'public/assets/for-northwood'
out.mkdir(parents=True, exist_ok=True)
doc = pdfium.PdfDocument(source / 'PNP.pdf')
pages = {}
assets = []
scale = 3

def crop(page, cell, name):
    if page not in pages:
        pages[page] = doc[page-1].render(scale=scale).to_pil().convert('RGB')
    row, col = divmod(cell-1, 3)
    x, y = 29.76 + col*178.583, 47.24 + row*249.449
    # Inset one PDF point to exclude the thin trim guides on the card edges.
    im = pages[page].crop(tuple(round(v*scale) for v in (x+1, y+1, x+177.583, y+248.449)))
    im.save(out / f'{name}.webp', quality=93)
    return f'/assets/for-northwood/{name}.webp'

def mirror(cell):
    row, col = divmod(cell-1, 3)
    return row*3 + 3-col

def add(code, name, group, page, cell, back, **extra):
    assets.append(dict(id='nw-'+code, type='card', name=name, group=group,
        groupLabel={'dialogue':'对话牌', 'character':'角色', 'fief':'领地', 'visit':'拜访指示牌'}[group],
        width=140, height=195.56, front=crop(page, cell, code), back=back,
        sourcePage=page, sourceCell=cell, **extra))

back = crop(2, 1, 'card-back')
suits = [('claws','爪',1), ('flowers','花',3), ('eyes','瞳',5), ('leaves','叶',7)]
for suit, label, page in suits:
    for value in range(1,9):
        add(f'{suit}-{value}', f'{label} · {value}', 'dialogue', page, value, back, suit=suit, number=value)

for value, cell in enumerate([1,8,7,6,5,4,3,2]):
    add(f'fief-{value}', f'领地 {value}', 'fief', 9, cell,
        crop(10, mirror(cell), f'fief-{value}-back'), number=value, stars=[4,3,2,1,1,2,3,4][value])
add('visit', '拜访指示／奖牌表', 'visit', 9, 9, crop(10,1,'visit-back'))

ranks = [('jack','骑士'), ('queen','女王'), ('king','国王'), ('prince','王子'), ('lady','贵妇'), ('baron','男爵')]
for suit, label, page, first in [('claws','爪',11,1), ('flowers','花',11,7), ('eyes','瞳',13,4), ('leaves','叶',15,1)]:
    for i, (rank, name) in enumerate(ranks):
        cell = first+i
        p = page
        if cell > 9:
            cell -= 9
            p += 2
        add(f'{suit}-{rank}', f'{label}之{name}', 'character', p, cell, back, suit=suit, rank=rank, advanced=i>=3)

(root / 'src/games/for-northwood-assets.js').write_text(
    '// Generated by scripts/extract-for-northwood.py\nexport const northwoodAssets = '
    + json.dumps(assets, ensure_ascii=False, indent=2) + ';\n', encoding='utf8')
shutil.copyfile(source / 'For_Northwood_-_Rules_20220827.pdf', out / 'rules-en.pdf')
print(f'Extracted {len(assets)} double-sided cards and copied the supplied rules.')
